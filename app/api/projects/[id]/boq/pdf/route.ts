import { prisma } from "@/lib/prisma";
import { calculateBOQ } from "@/lib/boq";
import {
  CONDUIT_PIPE_LENGTH_M,
  WIRE_COIL_LENGTH_M,
  JUNCTION_BOX_TYPES,
  parseExtraBoxes,
} from "@/lib/boq-config";
import { NextResponse } from "next/server";
import PDFDocument from "pdfkit";

export async function GET(
  _request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;

  const project = await prisma.project.findUnique({
    where: { id },
    include: {
      rooms: {
        orderBy: { id: "asc" },
        include: { points: { orderBy: { id: "asc" } } },
      },
    },
  });

  if (!project) {
    return NextResponse.json({ error: "Project not found." }, { status: 404 });
  }

  const boq = calculateBOQ(project);
  const extra = parseExtraBoxes(project.extraBoxes);
  const extraRows = JUNCTION_BOX_TYPES
    .map((type) => ({ type, qty: extra[type] }))
    .filter((r) => r.qty > 0);

  const isHalf = project.conduitMode === "HALF";
  const modeLabel = isHalf ? "Half conduit" : "Full conduit";

  const doc = new PDFDocument({ margin: 50, size: "A4" });
  const chunks: Buffer[] = [];

  doc.on("data", (chunk: Buffer) => chunks.push(chunk));

  const done = new Promise<Buffer>((resolve) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
  });

  // Header
  doc.fontSize(18).text("Bill of Quantities", { underline: false });
  doc.moveDown(0.4);
  doc.fontSize(12).text(project.clientName);
  doc.fontSize(10).fillColor("#555").text(project.siteAddress ?? "No address");
  doc.text(
    `${modeLabel} · Safety margin ${project.safetyMarginPercent}% · ${new Date().toLocaleDateString("en-GB")}`
  );
  doc.fillColor("#000");
  doc.moveDown();

  function sectionTitle(title: string) {
    doc.moveDown(0.6);
    doc.fontSize(12).fillColor("#000").text(title);
    doc.moveDown(0.3);
    doc.fontSize(9);
  }

  function row(left: string, right: string) {
    const y = doc.y;
    doc.text(left, 50, y, { width: 350, continued: false });
    doc.text(right, 400, y, { width: 140, align: "right" });
  }

  // 1. Fittings
  sectionTitle("1. Fittings schedule");
  if (boq.schedule.length === 0) {
    doc.fillColor("#555").text("None");
  } else {
    for (const r of boq.schedule) {
      row(r.name, String(r.quantity));
    }
  }

  // 2. Conduit
  sectionTitle(`2. Conduit (pipe) — ${CONDUIT_PIPE_LENGTH_M} m pipes`);
  if (boq.conduit.length === 0) {
    doc.fillColor("#555").text("None");
  } else {
    for (const r of boq.conduit) {
      row(
        `${r.sizeMm} mm · measured ${r.rawM} m · with margin ${r.withMarginM} m`,
        `${r.pipes} pipes`
      );
    }
  }

  // 3. Cable
  sectionTitle(`3. Cable (all circuits) — ${WIRE_COIL_LENGTH_M} m coils`);
  if (boq.wire.length === 0) {
    doc.fillColor("#555").text("None");
  } else {
    for (const r of boq.wire) {
      row(
        `${r.sizeMm2} mm² · measured ${r.rawM} m · with margin ${r.withMarginM} m`,
        `${r.coils} coils`
      );
    }
  }

  // 4. Boxes
  sectionTitle("4. Boxes & accessories");
  if (boq.boxes.length === 0) {
    doc.fillColor("#555").text("None (auto)");
  } else {
    for (const r of boq.boxes) {
      row(r.name, `${r.withMargin} (raw ${r.raw})`);
    }
  }
  if (extraRows.length > 0) {
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor("#000").text("Extra junction boxes (from plan)");
    doc.fontSize(9);
    for (const r of extraRows) {
      row(`${r.type} box`, String(r.qty));
    }
  }

  doc.moveDown(1.5);
  doc.fontSize(8).fillColor("#888").text(
    "Generated by Electrical Tools. Cable includes all circuits (in conduit and open). Conduit is pipe only."
  );

  doc.end();
  const pdf = await done;

  const safeName = project.clientName.replace(/[^\w\-]+/g, "_").slice(0, 40);

  return new NextResponse(new Uint8Array(pdf), {
    status: 200,
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="BOQ_${safeName}.pdf"`,
    },
  });
}